def test_absolute_extrusion_is_refused():
    src = [l.replace("M83 ; relative extrusion\n", "M82 ; absolute\n")
           for l in cube_gcode()]
    with pytest.raises(core.NonPlanarError) as e:
        core.process(src, amplitude_spec="-0.2")
    assert "relative E distances" in str(e.value)


def test_walls_are_never_touched():
    src = cube_gcode()
    out, _ = core.process(src, amplitude_spec="-0.2")
    wall_lines = [ln for ln in out if ln.startswith("G1 X0.000 Y0.000 E0.10000")]
    assert wall_lines, "the outer-wall moves vanished"
    assert all("Z" not in ln for ln in wall_lines)


def test_amplitude_as_percent_of_layer_height():
    src = cube_gcode(lh=0.2)
    amp, desc = core.resolve_amplitude("-150%", src)
    assert amp == pytest.approx(-0.3)
    assert "0.200" in desc
    amp, _ = core.resolve_amplitude("2x", src)
    assert amp == pytest.approx(0.4)
    amp, _ = core.resolve_amplitude("-0.25", src)
    assert amp == pytest.approx(-0.25)


def test_bad_amplitude_is_explained():
    with pytest.raises(core.NonPlanarError) as e:
        core.resolve_amplitude("wavy", cube_gcode())
    assert "Could not understand" in str(e.value)


def test_a_file_with_no_infill_is_returned_unchanged():
    src = ["M83\n", "G1 Z0.2\n", ";TYPE:Outer wall\n",
           "G1 X1.000 Y1.000 E0.10000\n", "G1 X9.000 Y1.000 E0.50000\n"]
    out, st = core.process(src, amplitude_spec="-0.2")
    assert out == src
    assert st["moves"] == 0


def test_frequency_changes_the_wave():
    src = cube_gcode()
    a, _ = core.process(src, amplitude_spec="-0.2", frequency=1.5)
    b, _ = core.process(src, amplitude_spec="-0.2", frequency=4.0)
    assert a != b


def test_zero_amplitude_leaves_geometry_flat():
    src = cube_gcode()
    out, st = core.process(src, amplitude_spec="0")
    assert st["max_wiggle"] == 0.0
    for x, y, z, e in moves(out):
        if z is not None:
            assert abs(z - round(z / 0.2) * 0.2) < 1e-9


def test_stats_describe_what_happened():
    src = cube_gcode()
    _, st = core.process(src, amplitude_spec="-0.2")
    assert st["sections"] == 5          # layers 4..8 are sparse
    assert st["moves"] > 0
    assert st["segments"] > st["moves"]
    assert st["extrusion_mode"] == "relative"
    assert st["solid_layers"] == 5      # 0.2 0.4 0.6 bottom skin, 1.8 solid, 2.0 top
    assert 0 < st["max_wiggle"] <= 0.2


def test_segment_length_controls_resolution():
    src = cube_gcode()
    _, coarse = core.process(src, amplitude_spec="-0.2", segment_mm=3.0)
    _, fine = core.process(src, amplitude_spec="-0.2", segment_mm=0.5)
    assert fine["segments"] > coarse["segments"]
    assert fine["moves"] == coarse["moves"]
